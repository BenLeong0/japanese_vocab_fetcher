"""
Pitch accent from the NHK accent dictionary (NHK日本語発音アクセント辞典), using the
data from https://github.com/javdejong/nhk-pronunciation.

The data is bundled in `api/data/nhk_accent.tsv.gz` (generated by
`scripts/build_nhk_accent.py`), so no network requests are made.
"""

import gzip
import re
from collections import defaultdict
from functools import cache
from pathlib import Path

from api.custom_types.alternative_string_types import URL, Kaki, Yomi
from api.custom_types.exception_types import APIError
from api.custom_types.response_types import ResponseItemNHK

NAME = "nhk"

DATA_PATH = Path(__file__).resolve().parent.parent / "data" / "nhk_accent.tsv.gz"

KANA_REGEX = re.compile(r"[ぁ-ゖァ-ヺー]+")


class NHKAPIError(APIError):
    pass


def response_factory(accent_list: list[Yomi] | None = None) -> ResponseItemNHK:
    return {
        "success": True,
        "error": None,
        "main_data": {
            "accent": [] if accent_list is None else accent_list,
        },
    }


def error_response_factory(error: NHKAPIError) -> ResponseItemNHK:
    return {
        "success": False,
        "error": error.to_dict(),
        "main_data": {
            "accent": [],
        },
    }


def main(word_list: list[Kaki]) -> dict[Kaki, ResponseItemNHK]:
    if not word_list:
        return {}

    try:
        word_index, reading_index = load_indices()
    except Exception as e:  # pylint: disable=broad-except
        error = NHKAPIError(
            f"failed to load NHK accent data: {e}", 500, URL(DATA_PATH.name)
        )
        print("An error occurred:", error.error_msg)
        return {word: error_response_factory(error) for word in word_list}

    return {
        word: response_factory(get_accents(word, word_index, reading_index))
        for word in word_list
    }


# Load data


AccentIndex = dict[str, list[Yomi]]


@cache
def load_indices() -> tuple[AccentIndex, AccentIndex]:
    """
    Return `(word_index, reading_index)`, mapping words (NHK headwords and kanji
    spellings) and hiragana readings respectively to lists of accents.
    Loaded once per process.
    """
    with gzip.open(DATA_PATH, "rt", encoding="utf-8") as f:
        lines = f.read().splitlines()
    return build_indices(lines)


def build_indices(lines: list[str]) -> tuple[AccentIndex, AccentIndex]:
    word_index: defaultdict[str, list[Yomi]] = defaultdict(list)
    reading_index: defaultdict[str, list[Yomi]] = defaultdict(list)
    for line in lines:
        word, accent = line.split("\t")
        word_index[word].append(Yomi(accent))
        reading = accent_to_reading(accent)
        if accent not in reading_index[reading]:
            reading_index[reading].append(Yomi(accent))
    return dict(word_index), dict(reading_index)


# Lookup


def get_accents(
    word: Kaki, word_index: AccentIndex, reading_index: AccentIndex
) -> list[Yomi]:
    accents = list(word_index.get(word, []))
    # Kana input can also match words usually written in kanji, eg はし -> 箸, 橋, 端
    if is_kana(word):
        for accent in reading_index.get(katakana_to_hiragana(word), []):
            if accent not in accents:
                accents.append(accent)
    return accents


# Helpers


def accent_to_reading(accent: str) -> str:
    """eg `あ' い・いれない` -> `あいいれない`"""
    return re.sub(r"[' ・]", "", accent)


def is_kana(word: str) -> bool:
    return KANA_REGEX.fullmatch(word) is not None


def katakana_to_hiragana(text: str) -> str:
    return "".join(chr(ord(c) - 0x60) if "ァ" <= c <= "ヶ" else c for c in text)
